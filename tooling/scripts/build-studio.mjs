export function buildStudio({ check = false } = {}) {
  const usedIcons = new Set([
    "play",
    "pause",
    "arrow-right",
    "plug",
    "unplug",
    "zap-off",
    "wrench",
    "plus",
  ]);
  const outputs = [
    ...pages.map((page) => [`${page.path.slice(1)}index.html`, renderPage(page)]),
    ...renderGalaxyPages(),
  ];
  for (const [path, html] of outputs) {
    const output = pagePath(path);
    for (const [, name] of html.matchAll(/data-lucide="([^"]+)"/g)) usedIcons.add(name);
    if (check) {
      if (readFileSync(output, "utf8") !== html)
        throw new Error(`${path} is stale; run npm run build.`);
    } else {
      mkdirSync(dirname(output), { recursive: true });
      writeFileSync(output, html);
    }
  }
  if (!check) {
    const output = websitePath("vendor/lucide/icons.js");
    mkdirSync(dirname(output), { recursive: true });
    const nodes = Object.fromEntries(
      [...usedIcons].sort().map((name) => {
        const key = name.replace(/(^|-)([a-z0-9])/g, (_, separator, letter) =>
          letter.toUpperCase(),
        );
        if (!icons[key]) throw new Error(`Unknown Lucide icon: ${name}`);
        return [name, icons[key]];
      }),
    );
    writeFileSync(
      output,
      `// Generated from the locked Lucide dependency; see ../lucide-LICENSE.txt.\nexport const iconNodes = ${JSON.stringify(nodes)};\n`,
    );
    copyFileSync(
      projectPath("node_modules/lucide/LICENSE"),
      websitePath("vendor/lucide-LICENSE.txt"),
    );
    console.log(`Built ${outputs.length} LEVNAT pages and local icons.`);
  }
}

if (isMain(import.meta.url)) buildStudio();
