const escape = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (char) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;",
      })[char],
  );
const icon = (name) => `<i data-lucide="${name}" aria-hidden="true"></i>`;
const navigation = [
  ["/services/", "Services", "services"],
  ["/work/", "Work", "work"],
  ["/approach/", "Process", "approach"],
];

const galaxyNavigation = `<script>
  (() => {
    const params = new URLSearchParams(location.search);
    const service = document.body.dataset.galaxyService;
    const requestedLayout = params.get("layout");
    const hasLayout = requestedLayout === "atom" || requestedLayout === "planets";
    if (!service && params.get("from") !== "galaxy" && !hasLayout) return;

    const layout = requestedLayout === "planets" ? "planets" : "atom";
    const requestedFocus = service || params.get("focus");
    const focus = ${JSON.stringify(PLANET_IDS)}.includes(requestedFocus) ? requestedFocus : null;
    const light = params.get("theme") === "light";
    const siteRoutes = ${JSON.stringify(["/", "/home/", ...pages.map((page) => page.path)])};
    const galaxyServices = ${JSON.stringify(pages.filter((page) => page.galaxyService).map((page) => page.path))};

    for (const link of document.querySelectorAll('a[href^="/"]')) {
      const destination = new URL(link.href);
      if (destination.origin !== location.origin) continue;
      const returning = destination.pathname === "/explore.html";
      if (!returning && !siteRoutes.includes(destination.pathname)) continue;

      if (returning && light) destination.pathname = "/home/";
      if (light && !returning && destination.pathname !== "/") destination.searchParams.set("theme", "light");
      destination.searchParams.set("layout", layout);
      if (returning || !galaxyServices.includes(destination.pathname)) {
        if (focus) destination.searchParams.set("focus", focus);
        if (!returning) destination.searchParams.set("from", "galaxy");
      }
      link.setAttribute("href", destination.pathname + destination.search + destination.hash);
    }
  })();
</script>`;

