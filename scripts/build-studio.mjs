const escape = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (char) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;",
      })[char],
  );
const icon = (name) => `<i data-lucide="${name}" aria-hidden="true"></i>`;
const navigation = [
  ["/services/", "Services", "services"],
  ["/work/", "Work", "work"],
  ["/approach/", "Approach", "approach"],
];

